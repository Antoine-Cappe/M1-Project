function [tlm,model]=EcriNetList3Dnew(tlm,model)

% Initialization
global fem_mesh_p;
global fem_mesh_e;
global fem_mesh_t;

tlm.conf.Resistor = 0;
tlm.conf.Capacitor = 0;

name1 = sprintf('%s.cir', tlm.conf.Name);        % Name of the file for the Net List
fid = fopen(name1, 'w');                         % Open the File

name2 = sprintf('%s.cor', tlm.conf.Name);        % Name of the file for the coordinates of each node
fie = fopen(name2, 'w');                         % Open the File

% Write Headers
fprintf(fid, '%s.cir\n', tlm.conf.Name);
fprintf(fid, '********************************************************************************\n');            
fprintf(fid, '*\n');            
fprintf(fid, '* Spice Netlist Generated by\n'); 
fprintf(fid, '*\n');            
fprintf(fid, '* BIOCAD Program\n');            
fprintf(fid, '* Release 1.0\n');            
fprintf(fid, '*\n');            
fprintf(fid, '* Authors: Vincent Senez\n'); 
fprintf(fid, '*\n');            
fprintf(fid, '* Release 1.0 : January 2019\n');          
fprintf(fid, '*\n');            
fprintf(fid, '********************************************************************************\n');

% Xyce-compatible analysis and output directives.
fprintf(fid, '.AC DEC %f %f %f\n', tlm.var.frequence.step, tlm.var.frequence.min, tlm.var.frequence.max);

% Modified by: Tina - Build connectivity mask for SPICE node validation
% This ensures electrode and measurement nodes are connected to the circuit
connected_mask = build_spice_node_mask(tlm, fem_mesh_p);

if ~isempty(connected_mask) && any(connected_mask)
    [tlm.ind.pt.elec1, moved1] = nearest_connected_node(tlm.ind.pt.elec1, fem_mesh_p, connected_mask);
    [tlm.ind.pt.elec2, moved2] = nearest_connected_node(tlm.ind.pt.elec2, fem_mesh_p, connected_mask);
    
    % Modified by: Tina - Log electrode node mapping decisions
    % Critical for debugging if results are unexpectedly high/low
    if moved1
        fprintf('\n\t . Warning: electrode 1 node was isolated; remapped to node %u', tlm.ind.pt.elec1);
    else
        fprintf('\n\t . Electrode 1 (excitation): node %u (connected)', tlm.ind.pt.elec1);
    end
    if moved2
        fprintf('\n\t . Warning: electrode 2 node was isolated; remapped to node %u', tlm.ind.pt.elec2);
    else
        fprintf('\n\t . Electrode 2 (return): node %u (connected)', tlm.ind.pt.elec2);
    end
    
    % Modified by: Tina - Store node remapping status for validation report
    tlm.node_mapping.elec1_remapped = moved1;
    tlm.node_mapping.elec2_remapped = moved2;
end

% Modified by: Tina - Extract measurement nodes (may differ from excitation electrodes)
% In 4-point measurement configuration, measurement nodes can be at different locations
mesu1 = tlm.ind.pt.elec1;
mesu2 = tlm.ind.pt.elec2;
measurement_mode = 'default';

if isfield(tlm.ind, 'pt') && isfield(tlm.ind.pt, 'mesu1') && ~isempty(tlm.ind.pt.mesu1)
    mesu1 = tlm.ind.pt.mesu1;
    measurement_mode = 'custom';
end
if isfield(tlm.ind, 'pt') && isfield(tlm.ind.pt, 'mesu2') && ~isempty(tlm.ind.pt.mesu2)
    mesu2 = tlm.ind.pt.mesu2;
    measurement_mode = 'custom';
end

% Modified by: Tina - Log measurement node configuration
fprintf('\n\t . Measurement nodes: mesu1=%u, mesu2=%u (%s mode)', mesu1, mesu2, measurement_mode);

% 4-point impedance measurement: Z = Rg * V(mesu2) / V(mesu1)
% In dB (Xyce notation): Z_dB = VDB(mesu2) - VDB(mesu1) + 20*log10(Rg)
% With Rg=50e-6 Ω: 20*log10(50e-6) ≈ -86.02 dB
if tlm.conf.points == 2
    fprintf(fid, '.PRINT AC FORMAT=CSV FREQ {VDB(%u,%u)-VDB(%u)-86} {VP(%u,%u)-VP(%u)}', ...
            tlm.ind.pt.elec2, tlm.ind.pt.elec1, tlm.ind.pt.elec1, ...
            tlm.ind.pt.elec2, tlm.ind.pt.elec1, tlm.ind.pt.elec1);
elseif tlm.conf.points == 4
    fprintf(fid, '.PRINT AC FORMAT=CSV FREQ {VDB(%u)-VDB(%u)-86} {VP(%u,%u)-VP(%u)}', ...
            mesu2, mesu1, ...
            tlm.ind.pt.elec1, mesu2, mesu1);
else
    fprintf(fid, '.PRINT AC FORMAT=CSV FREQ {VDB(%u,%u)-VDB(%u)-86} {VP(%u,%u)-VP(%u)}', ...
            tlm.ind.pt.elec2, tlm.ind.pt.elec1, tlm.ind.pt.elec1, ...
            tlm.ind.pt.elec2, tlm.ind.pt.elec1, tlm.ind.pt.elec1);
end

% Disable per-node VR() dumping by default
fprintf(fid, '\n');

% Modified by: Tina - Define SPICE voltage source for excitation (Vin)
fprintf(fid, 'Vin\t%u\t0\tDC 0 AC %f\n', tlm.ind.pt.elec2, tlm.var.v0); 
fprintf('\n\t . Excitation source: Vin connected to node %u with amplitude %.3e V', tlm.ind.pt.elec2, tlm.var.v0);

% Modified by: Tina - Define SPICE source impedance (Rg)
fprintf(fid, 'Rg\t%u\t0\t50e-5\n', tlm.ind.pt.elec1);  
fprintf('\n\t . Source impedance: Rg (50μΩ) connected to node %u', tlm.ind.pt.elec1);

%Write the value of all electrical components in the .cir file

for i=1:1:size(fem_mesh_p,2)  % Loop on the nodes

    % Save node coordinates
    fprintf(fie, '%u\t%f\t%f\t%f\n', i, fem_mesh_p(1,i), fem_mesh_p(2,i), fem_mesh_p(3,i));     
    
    if size(tlm.result{i},2)~=0  % if array for node i is filled in
        for j=7:7:size(tlm.result{i},2)
        
            % === OPTIMIZED: Replace massive if-elseif block with data-driven approach ===
            boundary_condition = tlm.result{i}{j};
            
            % Use helper function to get configuration for this boundary condition
            [boundary_cfg, is_dual_region] = get_boundary_condition_config(boundary_condition);
            
            if ~isempty(boundary_cfg)
                % Standard boundary conditions (0-14)
                write_resistor_capacitor_pair(fid, tlm, i, j, boundary_cfg);
                
            elseif is_special_boundary_electrode(fem_mesh_t, tlm, i, j)
                % Special case: exactly on electrode boundary
                write_electrode_boundary_components(fid, tlm, i, j);
                
            elseif is_special_boundary_membrane(fem_mesh_t, tlm, i, j, 1, 'MilOrga', 'Cytoplasme')
                % Special case: cell membrane
                write_dual_region_components(fid, tlm, i, j, 'mter', 'mbis');
                
            elseif is_special_boundary_membrane(fem_mesh_t, tlm, i, j, 2, 'MilOrga', 'Cytoplasme')
                % Special case: cell membrane (second cell)
                write_dual_region_components(fid, tlm, i, j, 'mter', 'mbis');
                
            elseif is_special_boundary_membrane(fem_mesh_t, tlm, i, j, 1, 'Nucleus', 'Cytoplasme')
                % Special case: nucleus membrane
                write_dual_region_components(fid, tlm, i, j, 'nter', 'nbis');
                
            elseif is_special_boundary_membrane(fem_mesh_t, tlm, i, j, 2, 'Nucleus', 'Cytoplasme')
                % Special case: nucleus membrane (second cell)
                write_dual_region_components(fid, tlm, i, j, 'nter', 'nbis');
                
            elseif is_special_boundary_membrane(fem_mesh_t, tlm, i, j, 1, 'Mitochon', 'Cytoplasme')
                % Special case: mitochondria membrane
                write_dual_region_components(fid, tlm, i, j, 'oter', 'obis');
                
            elseif is_special_boundary_membrane(fem_mesh_t, tlm, i, j, 2, 'Mitochon', 'Cytoplasme')
                % Special case: mitochondria membrane (second cell)
                write_dual_region_components(fid, tlm, i, j, 'oter', 'obis');
            end
        end
    end
    
    % === OPTIMIZED: Extract parasitic elements calculation ===
    write_parasitic_elements(fid, tlm, i, fem_mesh_e, fem_mesh_p);
end

fprintf(fid, '.END\n');

% Modified by: Tina - Generate comprehensive netlist generation summary
fprintf('\n\t . Netlist Generation Summary:');
fprintf('\n\t\t - Total nodes in mesh: %d', size(fem_mesh_p, 2));
fprintf('\n\t\t - Extracted resistors: %d', tlm.conf.Resistor);
fprintf('\n\t\t - Extracted capacitors: %d', tlm.conf.Capacitor);
fprintf('\n\t\t - Resistors + Capacitors: %d (%.1f elements per node)', ...
        tlm.conf.Resistor + tlm.conf.Capacitor, ...
        (tlm.conf.Resistor + tlm.conf.Capacitor) / size(fem_mesh_p, 2));

if (tlm.conf.Resistor + tlm.conf.Capacitor) < size(fem_mesh_p, 2)
    fprintf('\n\t\t . Warning: element count (%d) < node count (%d)', ...
        tlm.conf.Resistor + tlm.conf.Capacitor, size(fem_mesh_p, 2));
    fprintf('\n\t\t   This suggests many isolated nodes.');
end

fprintf('\n\t . Output files generated:');
fprintf('\n\t\t - Netlist: %s', sprintf('%s.cir', tlm.conf.Name));
fprintf('\n\t\t - Coordinates: %s', sprintf('%s.cor', tlm.conf.Name));

tlm.extraction.num_resistors = tlm.conf.Resistor;
tlm.extraction.num_capacitors = tlm.conf.Capacitor;
tlm.extraction.num_nodes_total = size(fem_mesh_p, 2);
tlm.extraction.extraction_density = (tlm.conf.Resistor + tlm.conf.Capacitor) / size(fem_mesh_p, 2);

fclose(fid);
fclose(fie);

end

%% ============ HELPER FUNCTIONS ============

function [boundary_cfg, is_dual_region] = get_boundary_condition_config(condition)
% Maps boundary condition codes (0-14) to configuration structure
% Eliminates need for massive if-elseif chain
    
    is_dual_region = false;
    
    % Configuration: {condition_value, suffix1, suffix2, suffix_is_swap}
    % suffix1 = node i suffix, suffix2 = node j suffix (or empty if same)
    config_map = {
        {0,  '',        '',        false};   % Normal region (no special boundary)
        {1,  'bis',     '',        false};   % Outer electrodes
        {2,  'ter',     '',        false};   % Organic medium <-> outer electrodes
        {3,  'mbis',    '',        false};   % Cytoplasm(1) <-> organic medium
        {4,  'mter',    '',        false};   % Organic medium <-> cytoplasm(1)
        {5,  'nbis',    '',        false};   % Cytoplasm(1) <-> nucleus(1)
        {6,  'nter',    '',        false};   % Nucleus(1) <-> cytoplasm(1)
        {7,  'obis',    '',        false};   % Cytoplasm(1) <-> mitochondria(1)
        {8,  'oter',    '',        false};   % Mitochondria(1) <-> cytoplasm(1)
        {9,  'mbis',    '',        false};   % Cytoplasm(2) <-> organic medium
        {10, 'mter',    '',        false};   % Organic medium <-> cytoplasm(2)
        {11, 'nbis',    '',        false};   % Cytoplasm(2) <-> nucleus(2)
        {12, 'nter',    '',        false};   % Nucleus(2) <-> cytoplasm(2)
        {13, 'obis',    '',        false};   % Cytoplasm(2) <-> mitochondria(2)
        {14, 'oter',    '',        false};   % Mitochondria(2) <-> cytoplasm(2)
    };
    
    boundary_cfg = [];
    for k = 1:length(config_map)
        if config_map{k}{1} == condition
            boundary_cfg = config_map{k};
            break;
        end
    end
end

function write_resistor_capacitor_pair(fid, tlm, i, j, boundary_cfg, varargin)
% Helper function to write resistor-capacitor pairs to netlist
% Handles boundary condition logic (node i vs node j on boundary)
% 
% Usage: write_resistor_capacitor_pair(fid, tlm, i, j, boundary_cfg)
%        write_resistor_capacitor_pair(fid, tlm, i, j, boundary_cfg, boundary_type, cell_index)

    condition = boundary_cfg{1};
    suffix_primary = boundary_cfg{2};
    
    % Determine which boundary to check
    if nargin < 6
        boundary_type = 'standard';
        cell_index = [];
    else
        boundary_type = varargin{1};
        cell_index = varargin{2};
    end
    
    % Determine boundary check based on condition
    node_on_boundary = det_node_on_boundary(tlm, i, j, condition, boundary_type, cell_index);
    
    % Get node suffixes based on boundary position
    if node_on_boundary
        % Node i is on boundary
        node_i_suffix = sprintf('%sbis', suffix_primary);
        node_j_suffix = i;
    else
        % Node j is on boundary
        node_i_suffix = i;
        node_j_suffix = sprintf('%sbis', suffix_primary);
    end
    
    % Write resistor if valid
    if tlm.result{i}{j-4} ~= -1
        fprintf(fid, 'R%u_%u\t%u\t%u\t%17.16e\n', ...
            i, tlm.result{i}{j-6}, node_i_suffix, node_j_suffix, tlm.result{i}{j-4});
        tlm.conf.Resistor = tlm.conf.Resistor + 1;
    end
    
    % Write capacitor if valid
    if tlm.result{i}{j-3} ~= 0
        fprintf(fid, 'C%u_%u\t%u\t%u\t%17.16e\n', ...
            i, tlm.result{i}{j-6}, node_i_suffix, node_j_suffix, tlm.result{i}{j-3});
        tlm.conf.Capacitor = tlm.conf.Capacitor + 1;
    end
end

function node_on_boundary = det_node_on_boundary(tlm, i, j, condition, varargin)
% Determine if node i or node j is on boundary
% Returns true if node i on boundary, false if node j on boundary
    
    if nargin < 4
        boundary_type = 'standard';
    else
        boundary_type = varargin{1};
    end
    
    if ismember(condition, [0, 1, 2])
        % Outer electrode boundaries
        node_on_boundary = (size(tlm.geom.boundaryEE{i}, 2) == 1);
    elseif ismember(condition, [3, 4])
        % Cytoplasm(1) <-> organic medium
        node_on_boundary = (size(tlm.geom.boundaryEC{1, i}, 2) == 1);
    elseif ismember(condition, [5, 6])
        % Nucleus(1) <-> cytoplasm(1)
        node_on_boundary = (size(tlm.geom.boundaryEN{1, i}, 2) == 1);
    elseif ismember(condition, [7, 8])
        % Mitochondria(1) <-> cytoplasm(1)
        node_on_boundary = (size(tlm.geom.boundaryEM{1, i}, 2) == 1);
    elseif ismember(condition, [9, 10])
        % Cytoplasm(2) <-> organic medium
        node_on_boundary = (size(tlm.geom.boundaryEC{2, i}, 2) == 1);
    elseif ismember(condition, [11, 12])
        % Nucleus(2) <-> cytoplasm(2)
        node_on_boundary = (size(tlm.geom.boundaryEN{2, i}, 2) == 1);
    elseif ismember(condition, [13, 14])
        % Mitochondria(2) <-> cytoplasm(2)
        node_on_boundary = (size(tlm.geom.boundaryEM{2, i}, 2) == 1);
    else
        node_on_boundary = false;
    end
end

function is_special = is_special_boundary_electrode(fem_mesh_t, tlm, i, j)
% Check if segment is on special boundary (solicitation electrode)
    is_special = (fem_mesh_t(5, i) == tlm.ind.dom.elec1) || ...
                 (fem_mesh_t(5, tlm.result{i}{j-6}) == tlm.ind.dom.elec1) || ...
                 (fem_mesh_t(5, tlm.result{i}{j-5}) == tlm.ind.dom.elec2) || ...
                 (fem_mesh_t(5, tlm.result{i}{j-6}) == tlm.ind.dom.elec2);
end

function is_special = is_special_boundary_membrane(fem_mesh_t, tlm, i, j, cell_num, region1, region2)
% Check if segment is on special boundary (cell membrane, nucleus membrane, etc.)
    
    % Get domain indices safely
    if cell_num == 1
        if strcmp(region1, 'Cytoplasme'), dom1 = tlm.ind.dom.Cytoplasme(1); else, return; end
        if strcmp(region2, 'MilOrga'), dom2 = tlm.ind.dom.MilOrga;
        elseif strcmp(region2, 'Nucleus'), dom2 = tlm.ind.dom.Nucleus(1);
        elseif strcmp(region2, 'Mitochon'), dom2 = tlm.ind.dom.Mitochon(1);
        else, return;
        end
    else
        if strcmp(region1, 'Cytoplasme'), dom1 = tlm.ind.dom.Cytoplasme(2); else, return; end
        if strcmp(region2, 'MilOrga'), dom2 = tlm.ind.dom.MilOrga;
        elseif strcmp(region2, 'Nucleus'), dom2 = tlm.ind.dom.Nucleus(2);
        elseif strcmp(region2, 'Mitochon'), dom2 = tlm.ind.dom.Mitochon(2);
        else, return;
        end
    end
    
    is_special = ((fem_mesh_t(5, tlm.result{i}{j-5}) == dom1) && (fem_mesh_t(5, tlm.result{i}{j-6}) == dom2)) || ...
                 ((fem_mesh_t(5, tlm.result{i}{j-6}) == dom1) && (fem_mesh_t(5, tlm.result{i}{j-5}) == dom2));
end

function write_electrode_boundary_components(fid, tlm, i, j)
% Write components for special electrode boundary
    
    % Impedance in organic medium
    if tlm.result{i}{j-4} ~= -1
        fprintf(fid, 'Rter%u_%u\t%uter\t%uter\t%17.16e\n', ...
            i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-4});
        tlm.conf.Resistor = tlm.conf.Resistor + 1;
    end
    if tlm.result{i}{j-3} ~= 0
        fprintf(fid, 'Cter%u_%u\t%uter\t%uter\t%17.16e\n', ...
            i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-3});
        tlm.conf.Capacitor = tlm.conf.Capacitor + 1;
    end
    
    % Impedance in solicitation electrode
    if tlm.result{i}{j-2} ~= -1
        fprintf(fid, 'Rbis%u_%u\t%ubis\t%ubis\t%17.16e\n', ...
            i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-2});
        tlm.conf.Resistor = tlm.conf.Resistor + 1;
    end
    if tlm.result{i}{j-1} ~= 0
        fprintf(fid, 'Cbis%u_%u\t%ubis\t%ubis\t%17.16e\n', ...
            i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-1});
        tlm.conf.Capacitor = tlm.conf.Capacitor + 1;
    end
end

function write_dual_region_components(fid, tlm, i, j, suffix1, suffix2)
% Write components for dual-region special boundaries
    
    % Impedance in first region
    if tlm.result{i}{j-4} ~= -1
        fprintf(fid, 'R%s%u_%u\t%%%s\t%%%s\t%17.16e\n', ...
            suffix1, i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-4});
        tlm.conf.Resistor = tlm.conf.Resistor + 1;
    end
    if tlm.result{i}{j-3} ~= 0
        fprintf(fid, 'C%s%u_%u\t%%%s\t%%%s\t%17.16e\n', ...
            suffix1, i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-3});
        tlm.conf.Capacitor = tlm.conf.Capacitor + 1;
    end
    
    % Impedance in second region
    if tlm.result{i}{j-2} ~= -1
        fprintf(fid, 'R%s%u_%u\t%%%s\t%%%s\t%17.16e\n', ...
            suffix2, i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-2});
        tlm.conf.Resistor = tlm.conf.Resistor + 1;
    end
    if tlm.result{i}{j-1} ~= 0
        fprintf(fid, 'C%s%u_%u\t%%%s\t%%%s\t%17.16e\n', ...
            suffix2, i, tlm.result{i}{j-6}, i, tlm.result{i}{j-6}, tlm.result{i}{j-1});
        tlm.conf.Capacitor = tlm.conf.Capacitor + 1;
    end
end

function write_parasitic_elements(fid, tlm, i, fem_mesh_e, fem_mesh_p)
% Unified function for all parasitic element generation
% Eliminates 6x duplication of boundary area calculations
    
    % Map of boundary types to their parasitic element configurations
    boundary_configs = {
        {'boundaryEE', @calculate_parasitic_EE};
        {'boundaryEC_1', @calculate_parasitic_EC};
        {'boundaryEC_2', @calculate_parasitic_EC};
        {'boundaryEN_1', @calculate_parasitic_EN};
        {'boundaryEN_2', @calculate_parasitic_EN};
        {'boundaryEM_1', @calculate_parasitic_EM};
        {'boundaryEM_2', @calculate_parasitic_EM};
    };
    
    for bc_idx = 1:length(boundary_configs)
        bc_name = boundary_configs{bc_idx}{1};
        bc_handler = boundary_configs{bc_idx}{2};
        
        % Parse boundary type information
        if contains(bc_name, 'EC')
            cell_num = str2double(bc_name(end));
            if size(tlm.geom.boundaryEC{cell_num, i}, 1) == 1
                area = compute_boundary_area(i, fem_mesh_e, fem_mesh_p);
                bc_handler(fid, tlm, i, area, cell_num);
            end
        elseif contains(bc_name, 'EN')
            cell_num = str2double(bc_name(end));
            if size(tlm.geom.boundaryEN{cell_num, i}, 1) == 1
                area = compute_boundary_area(i, fem_mesh_e, fem_mesh_p);
                bc_handler(fid, tlm, i, area, cell_num);
            end
        elseif contains(bc_name, 'EM')
            cell_num = str2double(bc_name(end));
            if size(tlm.geom.boundaryEM{cell_num, i}, 1) == 1
                area = compute_boundary_area(i, fem_mesh_e, fem_mesh_p);
                bc_handler(fid, tlm, i, area, cell_num);
            end
        elseif strcmp(bc_name, 'boundaryEE')
            if size(tlm.geom.boundaryEE{i}, 1) == 1
                area = compute_boundary_area(i, fem_mesh_e, fem_mesh_p);
                bc_handler(fid, tlm, i, area);
            end
        end
    end
end

function area = compute_boundary_area(node_i, fem_mesh_e, fem_mesh_p)
% OPTIMIZED: Single area calculation function replaces 6x duplication
% Computes total area of triangles containing node_i at a boundary
    
    area = 0;
    
    for j = 1:1:size(fem_mesh_e, 2)  % loop on triangles at interface
        if node_i == fem_mesh_e(1, j) || node_i == fem_mesh_e(2, j) || node_i == fem_mesh_e(3, j)
            % Calculate triangle side lengths
            d12 = sum((fem_mesh_p(:, fem_mesh_e(1, j)) - fem_mesh_p(:, fem_mesh_e(2, j))).^2)^0.5;
            d23 = sum((fem_mesh_p(:, fem_mesh_e(2, j)) - fem_mesh_p(:, fem_mesh_e(3, j))).^2)^0.5;
            d13 = sum((fem_mesh_p(:, fem_mesh_e(1, j)) - fem_mesh_p(:, fem_mesh_e(3, j))).^2)^0.5;
            
            % Use Heron's formula to get triangle area
            s = 0.5 * (d12 + d23 + d13);
            triangle_area = (s * (s - d12) * (s - d13) * (s - d23))^0.5;
            
            % Allocate 1/3 of triangle area to this node
            area = area + triangle_area / 3;
        end
    end
end

